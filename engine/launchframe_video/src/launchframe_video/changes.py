from typing import Any, Final

from launchframe_video.files import VIDEO, WORK, read_plain

FIELDS: Final = "fields.json"
VERSIONS: Final = "versions"
CHAT: Final = "chat.json"
CHANGES: Final = "changes"
"""``changes/<job id>.json``: one change job's result."""
SOURCE: Final = "source.tar.gz"
SOURCE_PATHS: Final = ("video.json", "audio.json", "STATE.md", "STORYBOARD.md", "DESIGN.md", "src", "public")
MAX_SOURCE_FILE: Final = 50 * 1024 * 1024
TIMING: Final = "public/audio/vo/timing.json"

WORDS_PER_SECOND: Final = 2.3
"""The kit's voice budget: words that fit a scene (``kit.mjs status``)."""
MAX_CHAT: Final = 1200
MAX_TEXT: Final = 400

_SKIP_KEYS: Final = frozenset(
    [
        "id",
        "component",
        "icon",
        "logo",
        "src",
        "file",
        "image",
        "img",
        "avatar",
        "seed",
        "color",
        "colour",
        "tone",
        "variant",
        "kind",
        "type",
        "at",
        "start",
        "delay",
        "dur",
        "duration",
        "frame",
        "frames",
        "x",
        "y",
        "w",
        "h",
        "width",
        "height",
        "size",
        "scale",
        "speed",
        "zoom",
        "pick",
        "index",
        "active",
        "selected",
    ]
)
_HEX: Final = re.compile(r"#[0-9a-fA-F]{6}")
_COLOUR_VALUE: Final = re.compile(r"#[0-9a-fA-F]{3,8}")
_FILE_VALUE: Final = re.compile(r"[\w\-/.]+\.(png|jpe?g|svg|webp|gif|mp3|wav|mp4|json)", re.I)
_TOKEN_VALUE: Final = re.compile(r"[a-z][a-z0-9_-]{0,15}")  # icon keys and the like, not words people read
_BRAND_COLOURS: Final = (
    ("bg", "Background"),
    ("fg", "Text"),
    ("accent", "Accent"),
    ("accent2", "Second accent"),
    ("muted", "Muted text"),
    ("surface", "Cards"),
    ("line", "Lines"),
    ("danger", "Problem red"),
    ("pass", "Success green"),
)


_FONT_ROLES: Final = (("font", "Headlines and copy"), ("ui", "Product screens"), ("mono", "Labels and code"))
_FONT_WEIGHTS: Final = (400, 500, 600, 700, 800)
_SIZE: Final = re.compile(r"fontSize:\s*(\d+(?:\.\d+)?)(?![\d.])")
_NAME: Final = re.compile(r"[A-Za-z0-9_-]{1,40}")
_SIZE_NAMES: Final = ("Biggest text", "Large text", "Medium text", "Text", "Small text", "Smallest text")


def font_choices(kit: Path) -> dict[str, Path]:
    """Fonts the renderer has (the kit's ``@fontsource`` packages): family → package folder."""
    out: dict[str, Path] = {}
    root = kit / "node_modules" / "@fontsource"
    for pkg in sorted(root.iterdir()) if root.is_dir() else []:
        try:
            family = json.loads((pkg / "metadata.json").read_text())["family"]
        except (OSError, ValueError, KeyError):
            continue
        if isinstance(family, str):
            out[family] = pkg
    return out


def fonts_module(choices: dict[str, Path], families: list[str]) -> str:
    """``src/lib/fonts.gen.ts`` embedding ``families`` (latin, normal, the usual weights)."""
    import base64

    rows = []
    for family in dict.fromkeys(families):
        pkg = choices.get(family)
        if pkg is None:
            continue
        for w in _FONT_WEIGHTS:
            f = pkg / "files" / f"{pkg.name}-latin-{w}-normal.woff2"
            if f.is_file():
                data = base64.b64encode(f.read_bytes()).decode()
                rows.append(
                    f'  {{ family: {json.dumps(family)}, weight: {w}, style: "normal", data: "{data}" }}'
                )
    return (
        "// generated by scripts/embed-fonts.mjs — do not edit or read\nexport const FONTS = [\n"
        + ",\n".join(rows)
        + "\n];\n"
    )


class BadEditError(ValueError):
    """An edit that can't be applied; the message is shown as it is."""


# ---------------------------------------------------------------- reading the video's values


def _read_json(path: Path) -> Any:
    raw = read_plain(path)
    try:
        return json.loads(raw) if raw is not None else None
    except ValueError:
        return None


def _label(path: list[str | int]) -> str:
    parts: list[str] = []
    for p in path:
        if isinstance(p, int):
            parts.append(str(p + 1))
        else:
            words = re.sub(r"(?<=[a-z])(?=[A-Z0-9])", " ", p).replace("_", " ").strip()
            parts.append(words[:1].upper() + words[1:].lower())
    return " · ".join(parts)


def _leaves(value: Any, path: list[str | int], out: list[dict[str, Any]]) -> None:
    key = next((p for p in reversed(path) if isinstance(p, str)), "")
    if key.lower() in _SKIP_KEYS:
        return
    if isinstance(value, dict):
        for k, v in value.items():
            _leaves(v, [*path, str(k)], out)
    elif isinstance(value, list):
        for i, v in enumerate(value):
            _leaves(v, [*path, i], out)
    elif isinstance(value, bool):
        return
    elif isinstance(value, int | float):
        out.append({"path": path, "label": _label(path), "kind": "number", "value": value})
    elif isinstance(value, str):
        t = value.strip()
        if not t or _COLOUR_VALUE.fullmatch(t) or _FILE_VALUE.fullmatch(t) or _TOKEN_VALUE.fullmatch(t):
            return
        out.append({"path": path, "label": _label(path), "kind": "text", "value": value})


def read_fields(work: Path, fonts: list[str] | None = None) -> dict[str, Any] | None:
    """What can be edited in the video in ``work/`` (``None`` when its ``video.json`` can't be read)."""
    spec = _read_json(work / "video.json")
    if not isinstance(spec, dict) or not isinstance(spec.get("scenes"), list):
        return None
    fps = int((spec.get("meta") or {}).get("fps") or 60)
    timing = _read_json(work / TIMING)
    spoken = {
        str(t.get("scene")): str(t.get("text") or "")
        for t in (timing if isinstance(timing, list) else [])
        if isinstance(t, dict)
    }
    scenes = []
    for s in spec["scenes"]:
        if not isinstance(s, dict):
            continue
        sid, frames = str(s.get("id", "")), int(s.get("frames") or 0)
        if not _NAME.fullmatch(sid):
            continue  # ids become file names; kit.mjs refuses such a video anyway
        fields: list[dict[str, Any]] = []
        _leaves(s.get("props") or {}, ["props"], fields)
        for f in fields:
            f["id"] = f"{sid}/" + "/".join(str(p) for p in f["path"])
            f["label"] = _label(f["path"][1:])
        comp = str(s.get("component") or "")
        code = read_plain(work / "src" / "scenes" / f"{comp}.tsx") if _NAME.fullmatch(comp) else None
        sizes: dict[float, int] = {}
        for m in _SIZE.finditer(code or ""):
            px = float(m.group(1))
            sizes[px] = sizes.get(px, 0) + 1
        ranked = sorted(sizes, reverse=True)
        for i, px in enumerate(ranked):
            name = _SIZE_NAMES[min(i, len(_SIZE_NAMES) - 1)] if len(ranked) > 1 else "Text"
            if i == len(ranked) - 1 and len(ranked) > 2:
                name = "Smallest text"
            value = int(px) if px.is_integer() else px
            fields.append(
                {
                    "id": f"{sid}/@size/{value}",
                    "path": ["@size", value],
                    "label": f"{name} size ({sizes[px]}×)",
                    "kind": "size",
                    "value": value,
                }
            )
        vo = spoken.get(sid) or str(s.get("vo") or "")
        scenes.append(
            {
                "id": sid,
                "name": str(s.get("name") or sid),
                "seconds": round(frames / fps, 2),
                "vo": vo,
                "voBudget": int(max(0.0, frames / fps - 0.3) * WORDS_PER_SECOND),
                "fields": fields,
            }
        )
    brand = spec.get("brand") or {}
    colours = [
        {"key": k, "label": label, "value": str(brand[k]).lower()}
        for k, label in _BRAND_COLOURS
        if isinstance(brand.get(k), str) and _HEX.fullmatch(brand[k])
    ]
    families = sorted(set(fonts or []))
    font_rows = [
        {"key": k, "label": label, "value": str(brand[k])}
        for k, label in _FONT_ROLES
        if isinstance(brand.get(k), str) and brand[k]
    ]
    return {"scenes": scenes, "brand": colours, "fonts": font_rows, "fontChoices": families}


def write_fields(run_dir: Path, fonts: list[str] | None = None) -> dict[str, Any] | None:
    fields = read_fields(run_dir / WORK, fonts)
    if fields is not None:
        _write_json(run_dir / FIELDS, fields)
    return fields


def load_fields(run_dir: Path) -> dict[str, Any] | None:
    out = _read_json(run_dir / FIELDS)
    return out if isinstance(out, dict) else None


# ---------------------------------------------------------------- checking and applying an edit


def check_edit(fields: dict[str, Any], edit: dict[str, Any]) -> dict[str, Any]:
    """The edit with only real changes, each checked against what the video holds, or
    :class:`BadEditError` in plain words. ``edit``: ``values`` {field id: value}, ``vo`` {scene: text},
    ``brand`` {key: #hex}."""
    known = {f["id"]: f for s in fields.get("scenes", []) for f in s.get("fields", [])}
    scenes = {s["id"]: s for s in fields.get("scenes", [])}
    brand = {b["key"]: b for b in fields.get("brand", [])}
    fonts = {b["key"]: b for b in fields.get("fonts", [])}
    out: dict[str, Any] = {"values": {}, "vo": {}, "brand": {}, "fonts": {}}
    for fid, value in (edit.get("values") or {}).items():
        f = known.get(fid)
        if f is None:
            raise BadEditError("that field isn't in this video any more; reload the page")
        if f["kind"] in ("number", "size"):
            if isinstance(value, bool) or not isinstance(value, int | float):
                raise BadEditError(f"{f['label']} must be a number")
            if f["kind"] == "size" and not (max(8, f["value"] / 2) <= value <= min(400, f["value"] * 2)):
                raise BadEditError(
                    f"{f['label']}: keep it between half and double its size"
                    f" ({max(8, f['value'] / 2):g}–{min(400, f['value'] * 2):g} px)"
                )
            if value == f["value"]:
                continue
        else:
            value = str(value)
            if not value.strip():
                raise BadEditError(f"{f['label']} can't be empty")
            limit = min(MAX_TEXT, max(2 * len(f["value"]), len(f["value"]) + 30, 40))
            if len(value) > limit:
                raise BadEditError(
                    f"{f['label']} is too long for its place on screen ({len(value)} of {limit} characters);"
                    " ask in the chat for a bigger change"
                )
            if value == f["value"]:
                continue
        out["values"][fid] = value
    for sid, text in (edit.get("vo") or {}).items():
        s = scenes.get(sid)
        if s is None:
            raise BadEditError("that scene isn't in this video any more; reload the page")
        text = " ".join(str(text).split())
        if text == s["vo"]:
            continue
        if not text:
            raise BadEditError(f"the voice line in “{s['name']}” can't be empty")
        words, budget = len(text.split()), max(s["voBudget"], len(s["vo"].split()))
        if words > budget:
            raise BadEditError(
                f"the voice line in “{s['name']}” has {words} words; about {budget} fit its"
                f" {s['seconds']:g} seconds. Shorten it, or ask for a fix in the chat and it will be fixed"
            )
        out["vo"][sid] = text
    for key, value in (edit.get("brand") or {}).items():
        b = brand.get(key)
        if b is None:
            raise BadEditError("that colour isn't in this video")
        v = str(value).strip().lower()
        if not _HEX.fullmatch(v):
            raise BadEditError(f"{b['label']} must be a colour like #1A2B3C")
        if v != b["value"]:
            out["brand"][key] = v
    for key, value in (edit.get("fonts") or {}).items():
        b = fonts.get(key)
        if b is None:
            raise BadEditError("that font isn't in this video")
        v = str(value).strip()
        if v not in fields.get("fontChoices", []):
            raise BadEditError(f"{v or 'that font'} isn't one of the fonts the video can use")
        if v != b["value"]:
            out["fonts"][key] = v
    if not (out["values"] or out["vo"] or out["brand"] or out["fonts"]):
        raise BadEditError("nothing changed")
    return out


def _set(obj: Any, path: list[str | int], value: Any) -> None:
    for p in path[:-1]:
        obj = obj[p]
    obj[path[-1]] = value


def apply_values(work: Path, edit: dict[str, Any], fields: dict[str, Any]) -> list[str]:
    """Write ``edit`` (already checked) into ``work/video.json`` and the voice timing; the scenes it
    touches, in order."""
    spec = _read_json(work / "video.json")
    if not isinstance(spec, dict):
        raise BadEditError("the video's file can't be read")
    paths = {f["id"]: f["path"] for s in fields["scenes"] for f in s["fields"]}
    by_id = {str(s.get("id")): s for s in spec.get("scenes", []) if isinstance(s, dict)}
    touched: set[str] = set()
    sizes: dict[str, dict[float, float]] = {}
    for fid, value in edit.get("values", {}).items():
        sid = fid.split("/", 1)[0]
        if paths.get(fid, [None])[0] == "@size":
            sizes.setdefault(sid, {})[float(paths[fid][1])] = value
            touched.add(sid)
            continue
        try:
            _set(by_id[sid], paths[fid], value)
        except (KeyError, IndexError, TypeError) as e:
            raise BadEditError("the video changed since the page loaded; reload and try again") from e
        touched.add(sid)
    for sid, text in edit.get("vo", {}).items():
        if sid in by_id:
            by_id[sid]["vo"] = text
    if edit.get("brand") or edit.get("fonts"):
        spec.setdefault("brand", {}).update(edit.get("brand") or {})
        spec["brand"].update(edit.get("fonts") or {})
        touched.update(by_id)  # every scene uses the brand
    for sid, change in sizes.items():
        comp = str(by_id[sid].get("component") or "")
        if not _NAME.fullmatch(comp):
            raise BadEditError("that scene's file can't be changed")
        file = work / "src" / "scenes" / f"{comp}.tsx"
        code = read_plain(file)
        if code is None:
            raise BadEditError("that scene's file can't be read")

        def resize(m: re.Match[str], change: dict[float, float] = change) -> str:
            new = change.get(float(m.group(1)))
            return m.group(0) if new is None else f"fontSize: {new:g}"

        no_links(work, "src/scenes")
        write_bytes(file, _SIZE.sub(resize, code).encode())
    _write_json(work / "video.json", spec, indent=2)
    if edit.get("vo"):
        timing = _read_json(work / TIMING)
        if isinstance(timing, list):
            for t in timing:
                if isinstance(t, dict) and str(t.get("scene")) in edit["vo"]:
                    t["text"] = edit["vo"][str(t["scene"])]
            _write_json(work / TIMING, timing, indent=2)
    return [sid for sid in by_id if sid in touched]


def voice_start_s(work: Path, scene: str, fps: int = 60) -> float:
    """When the scene's voice line starts within the scene, in seconds (0 when unknown)."""
    timing = _read_json(work / TIMING)
    for t in timing if isinstance(timing, list) else []:
        if isinstance(t, dict) and str(t.get("scene")) == scene:
            try:
                return float(t.get("frame") or 0) / fps
            except (TypeError, ValueError):
                return 0.0
    return 0.0


# ---------------------------------------------------------------- files the worker writes in work/


def no_links(root: Path, *rels: str) -> None:
    """Make each path below ``root`` safe to write: a link anywhere on the way is removed (the agent can
    plant one to send a write elsewhere) and folders are created."""
    for rel in rels:
        p = root
        for part in Path(rel).parts:
            p = p / part
            if p.is_symlink():
                p.unlink()
        if not rel.endswith((".json", ".mp3", ".txt", ".wav")):
            p.mkdir(parents=True, exist_ok=True)


def _write_json(path: Path, data: Any, indent: int | None = None) -> None:
    write_bytes(path, json.dumps(data, indent=indent, ensure_ascii=False).encode())


def write_bytes(path: Path, data: bytes) -> None:
    """Write a file atomically, replacing (never following) a link at ``path``. The temporary file has an
    unpredictable name and is created new (``mkstemp``: O_EXCL), so nothing planted beforehand, such as a hard
    link to a file elsewhere, is ever written through."""
    import tempfile

    fd, name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".part", dir=path.parent)
    tmp = Path(name)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        tmp.chmod(0o644)
        tmp.replace(path)
    except BaseException:
        with contextlib.suppress(OSError):
            tmp.unlink()
        raise


# ---------------------------------------------------------------- versions


def _index(run_dir: Path) -> dict[str, Any]:
    out = _read_json(run_dir / VERSIONS / "index.json")
    return (
        out
        if isinstance(out, dict) and isinstance(out.get("versions"), list)
        else {"current": 0, "versions": []}
    )


def versions(run_dir: Path) -> dict[str, Any]:
    """``{"current": n, "versions": [{n, at, kind, note, costUsd, minutes}]}``, oldest first."""
    return _index(run_dir)


def _pack(work: Path) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel in SOURCE_PATHS:
            top = work / rel
            if top.is_symlink() or not top.exists():
                continue
            files = [top] if top.is_file() else []
            if top.is_dir():
                for dirpath, dirnames, filenames in os.walk(top):  # never follows links
                    dirnames[:] = [d for d in dirnames if not (Path(dirpath) / d).is_symlink()]
                    files += [Path(dirpath) / n for n in filenames]
            for f in files:
                try:
                    fd = os.open(f, os.O_RDONLY | os.O_NOFOLLOW)
                except OSError:
                    continue  # a link or gone
                with os.fdopen(fd, "rb") as fh:
                    st = os.fstat(fh.fileno())
                    if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_SOURCE_FILE:
                        continue
                    info = tarfile.TarInfo(str(f.relative_to(work)))
                    info.size, info.mtime, info.mode = st.st_size, int(st.st_mtime), 0o644
                    tar.addfile(info, fh)
    return buf.getvalue()


def snapshot(run_dir: Path, *, kind: str, note: str, cost_usd: float = 0.0, minutes: float = 0.0) -> int:
    """Save the current video (``video.mp4`` beside ``work/``) and its sources as the next version."""
    idx = _index(run_dir)
    n = max([int(v["n"]) for v in idx["versions"]] + [0]) + 1
    d = run_dir / VERSIONS / str(n)
    d.mkdir(parents=True, exist_ok=False)
    shutil.copyfile(run_dir / VIDEO, d / VIDEO)
    (d / SOURCE).write_bytes(_pack(run_dir / WORK))
    if (run_dir / FIELDS).is_file():
        shutil.copyfile(run_dir / FIELDS, d / FIELDS)
    idx["versions"].append(
        {
            "n": n,
            "at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "kind": kind,
            "note": note[:300],
            "costUsd": round(cost_usd, 4),
            "minutes": round(minutes, 2),
        }
    )
    idx["current"] = n
    _prune(run_dir, idx)
    (run_dir / VERSIONS).mkdir(exist_ok=True)
    _write_json(run_dir / VERSIONS / "index.json", idx, indent=2)
    return n


KEEP_VERSIONS = 10
"""Versions kept per video, so they can't fill the disk. A new version is the live one: only older ones go."""


def _prune(run_dir: Path, idx: dict[str, Any]) -> None:
    keep = sorted(idx["versions"], key=lambda v: int(v["n"]), reverse=True)[:KEEP_VERSIONS]
    kept = {int(v["n"]) for v in keep}
    for v in idx["versions"]:
        if int(v["n"]) not in kept:
            d = run_dir / VERSIONS / str(int(v["n"]))
            if d.is_dir() and not d.is_symlink():
                shutil.rmtree(d)
    idx["versions"] = sorted(keep, key=lambda v: int(v["n"]))


def version_file(run_dir: Path, n: int) -> Path | None:
    p = run_dir / VERSIONS / str(int(n)) / VIDEO
    return p if p.is_file() and not p.is_symlink() else None


def restore(run_dir: Path, n: int) -> None:
    """Make version ``n`` the current one again: its sources back in ``work/`` and its video served."""
    idx = _index(run_dir)
    if not any(int(v["n"]) == n for v in idx["versions"]):
        raise BadEditError(f"there is no version {n}")
    d = run_dir / VERSIONS / str(n)
    work = run_dir / WORK
    for rel in SOURCE_PATHS:  # clear what the version will bring back (links removed, never followed)
        p = work / rel
        if p.is_symlink() or p.is_file():
            p.unlink()
        elif p.is_dir():
            shutil.rmtree(p)
    with tarfile.open(d / SOURCE, mode="r:gz") as tar:
        tar.extractall(work, filter="data")
    shutil.copyfile(d / VIDEO, run_dir / VIDEO)
    if (d / FIELDS).is_file():
        shutil.copyfile(d / FIELDS, run_dir / FIELDS)
    idx["current"] = n
    _write_json(run_dir / VERSIONS / "index.json", idx, indent=2)


def adopt(run_dir: Path, fonts: list[str] | None = None) -> int:
    """A video made before versions existed: its fields and version 1. Returns the current version."""
    if not (run_dir / FIELDS).is_file():
        write_fields(run_dir, fonts)
    idx = _index(run_dir)
    if idx["versions"]:
        return int(idx["current"])
    return snapshot(run_dir, kind="first", note="The first video")


# ---------------------------------------------------------------- the fix chat


def load_chat(run_dir: Path) -> list[dict[str, Any]]:
    out = _read_json(run_dir / CHAT)
    return out if isinstance(out, list) else []


def add_chat(run_dir: Path, message: dict[str, Any]) -> list[dict[str, Any]]:
    chat = load_chat(run_dir)
    chat.append({"at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), **message})
    _write_json(run_dir / CHAT, chat, indent=2)
    return chat


def save_change(run_dir: Path, job_id: str, result: dict[str, Any]) -> None:
    (run_dir / CHANGES).mkdir(exist_ok=True)
    _write_json(run_dir / CHANGES / f"{job_id}.json", result, indent=2)


