"""Changes to a finished video: field edits (no AI), chat fixes (a short agent session) and versions.

Beside ``work/`` (the agent's folder), written only by the worker:

* ``fields.json``: what the person can edit directly, read from ``work/video.json`` and the voice-over
  timing after every change: each scene's visible texts and numbers, its voice line (with a word budget)
  and the brand colours. The API reads this, never ``work/``.
* ``versions/index.json`` and ``versions/<n>/``: every made or changed video. ``video.mp4`` (what it looked
  like), ``fields.json`` and ``source.tar.gz`` (the agent's editable files: ``video.json``, ``audio.json``,
  notes, ``src/``, ``public/``; regular files only, never links), so a version can be restored.
* ``chat.json``: the fix chat (the person's messages and the agent's replies).

Edits change values at known places in ``video.json``; the kit re-renders only the scenes whose values
changed. A changed voice line is re-recorded and re-mixed; it must still fit its scene.
"""

