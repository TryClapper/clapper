// Embeds font files as base64 into src/lib/fonts.gen.ts, so every weight a scene uses is really there (a missing
// weight silently renders as the nearest one: 400 text comes out at 500, 600 at 700).
//
//   node scripts/embed-fonts.mjs                 the families in video.json brand (font, ui, mono) + Inter
//   node scripts/embed-fonts.mjs "Inter Tight" "Inter" "JetBrains Mono"
//   node scripts/embed-fonts.mjs --list          the installed families and their weights
//
// Each family gets every installed weight from 400 to 800 (latin, normal). Only installed @fontsource packages
// can be embedded; for any other font (a paid or custom one) pick the closest installed family.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = "node_modules/@fontsource";
const installed = new Map();
for (const dir of existsSync(ROOT) ? readdirSync(ROOT) : []) {
  try {
    const m = JSON.parse(readFileSync(path.join(ROOT, dir, "metadata.json"), "utf8"));
    installed.set(m.family, { dir, weights: m.weights.filter((w) => w >= 400 && w <= 800) });
  } catch {}
}
const args = process.argv.slice(2);
if (args[0] === "--list") {
  for (const [family, { weights }] of installed) console.log(`${family}: ${weights.join(", ")}`);
  process.exit(0);
}
let families = args;
if (!families.length) {
  const brand = existsSync("video.json") ? JSON.parse(readFileSync("video.json", "utf8")).brand ?? {} : {};
  families = [brand.font, brand.ui, brand.mono, "Inter", "Instrument Serif"].filter(Boolean); // the serif for quoted cards
}
families = [...new Set(families)];
const missing = families.filter((f) => !installed.has(f));
if (missing.length) {
  console.error(`not installed: ${missing.join(", ")}. Installed: ${[...installed.keys()].join(", ")}. Use the closest installed family.`);
  process.exit(1);
}
const files = families.flatMap((family) => {
  const { dir, weights } = installed.get(family);
  return weights.map((weight) => ({ family, weight, file: path.join(ROOT, dir, "files", `${dir}-latin-${weight}-normal.woff2`) }))
    .filter((f) => existsSync(f.file));
});
const body = files
  .map((f) => `  { family: ${JSON.stringify(f.family)}, weight: ${f.weight}, style: "normal", data: "${readFileSync(f.file).toString("base64")}" }`)
  .join(",\n");
writeFileSync("src/lib/fonts.gen.ts", `// generated by scripts/embed-fonts.mjs — do not edit or read\nexport const FONTS = [\n${body}\n];\n`);
console.log(`embedded ${files.length} font files: ${families.map((f) => `${f} ${installed.get(f).weights.join("/")}`).join(" · ")}`);
